def text_size(text, scale=2):
    text = str(text)
    if not text:
        return 0, 7 * scale
    width = len(text) * 6 * scale - scale
    height = 7 * scale
    return width, height


def draw_text(surface, text, x, y, color, scale=2):
    cursor_x = int(x)
    for char in str(text).upper():
        glyph = GLYPHS.get(char, GLYPHS[" "])
        for row_index, row in enumerate(glyph):
            for col_index, value in enumerate(row):
                if value == "1":
                    rect = pygame.Rect(
                        cursor_x + col_index * scale,
                        int(y) + row_index * scale,
                        scale,
                        scale,
                    )
                    pygame.draw.rect(surface, color, rect)
        cursor_x += 6 * scale


def draw_text_centered(surface, text, center, color, scale=2):
    width, height = text_size(text, scale)
    x = int(center[0] - width / 2)
    y = int(center[1] - height / 2)
    draw_text(surface, text, x, y, color, scale)
